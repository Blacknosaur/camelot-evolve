    func testConsensusRejectsMovingForegroundAndDegenerateSupport() throws {
        let expected = CameraTransform(values: [1.04, -0.03, 0.02, 0.02, 1.04, -0.01, 0.025, -0.02, 1])
        var matches: [CameraFeatureRegistration.Match] = []
        for row in 0..<6 {
            for column in 0..<8 {
                let source = CGPoint(x: 0.08 + Double(column) * 0.11, y: 0.08 + Double(row) * 0.13)
                matches.append(.init(source: source, target: try XCTUnwrap(expected.point(source))))
            }
        }
        for i in 0..<20 {
            let source = CGPoint(x: 0.1 + Double(i % 5) * 0.14, y: 0.6 + Double(i / 5) * 0.08)
            matches.append(.init(source: source, target: .init(x: source.x - 0.08, y: source.y + 0.03)))
        }
        let fitted = try XCTUnwrap(CameraFeatureRegistration.consensus(matches, size: .init(width: 640, height: 360)))
        for source in GroundFieldOverlay.rectangle {
            let target = try XCTUnwrap(expected.point(source)), actual = try XCTUnwrap(fitted.point(source))
            XCTAssertEqual(actual.x, target.x, accuracy: 0.0001)
            XCTAssertEqual(actual.y, target.y, accuracy: 0.0001)
        }
        let line = (0..<20).map { i in
            let p = CGPoint(x: Double(i) / 20, y: 0.4)
            return CameraFeatureRegistration.Match(source: p, target: p)
        }
        XCTAssertNil(CameraFeatureRegistration.consensus(line, size: .init(width: 640, height: 360)))
    }

